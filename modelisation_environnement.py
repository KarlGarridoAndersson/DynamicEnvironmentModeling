from scipy.signal import argrelextrema

# ÉTAPE 0: Recalculer N_actif(t) et S(t) si nécessaire
# (Au cas où compute_health_bicolor n'aurait pas été exécutée)

alpha, beta, delta, gamma = best
t_end  = T_te + D_te
t_end_max = t_end.max()
